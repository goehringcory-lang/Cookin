/** Every library lunch. `items` (shared LunchIdea field) = first choice of each required group. */
export const LUNCH_LIBRARY: readonly LibraryLunch[] = RAW.map((l) => ({
  ...l,
  items: l.ingredients.filter((i) => !i.optional).map((i) => i.anyOf[0]),
}));

const BY_ID = new Map(LUNCH_LIBRARY.map((l) => [l.id, l]));

export function getLunchIdea(id: string): LibraryLunch | undefined {
  return BY_ID.get(id);
}

/** Every catalog id the library can ask for. */
export function libraryCatalogIds(): string[] {
  const ids = new Set<string>();
  for (const l of LUNCH_LIBRARY) for (const ing of l.ingredients) ing.anyOf.forEach((i) => ids.add(i));
  return [...ids].sort();
}
