const { chromium, devices } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type()==='error') errs.push(m.text()); });
  const S = process.argv[2];
  await p.goto('http://localhost:4173');
  await p.screenshot({ path: S+'/1-welcome.png' });
  await p.getByRole('button', { name: "Let's go" }).click();
  await p.getByRole('button', { name: /Select common/ }).click();
  await p.getByRole('button', { name: /Bucatini/ }).click().catch(()=>p.getByText('Show all').click());
  await p.screenshot({ path: S+'/2-pantry.png' });
  await p.getByRole('button', { name: /Next category/ }).click();
  await p.waitForTimeout(400);
  await p.screenshot({ path: S+'/3-next-cat.png' });
  await p.getByLabel('Search ingredients').fill('tahini');
  await p.screenshot({ path: S+'/4-search.png' });
  await p.getByRole('button', { name: /Tahini/ }).click();
  await p.getByLabel('Search ingredients').fill('za atar spice blend x');
  await p.getByRole('button', { name: /Add “/ }).click();
  // reload to test resume
  await p.reload();
  await p.screenshot({ path: S+'/5-resume.png' });
  if (await p.getByRole('button', { name: /Pick up/ }).count()) await p.getByRole('button', { name: /Pick up/ }).click();
  console.log('count', await p.locator('.ob-count').first().textContent());
  await p.getByRole('button', { name: /Next: Fridge/ }).click();
  await p.getByRole('button', { name: /Select common/ }).click();
  await p.getByRole('button', { name: /Undo/ }).click();
  await p.getByRole('button', { name: /Select common/ }).click();
  await p.screenshot({ path: S+'/6-fridge.png' });
  await p.getByRole('button', { name: /Next: Freezer/ }).click();
  await p.getByRole('button', { name: /Next: Always-buy/ }).click();
  await p.screenshot({ path: S+'/7-staples.png', fullPage: true });
  await p.getByRole('button', { name: 'Goldfish crackers' }).click();
  await p.getByPlaceholder('e.g. sparkling water').fill('Sparkling water');
  await p.getByRole('button', { name: 'Add', exact: true }).click();
  await p.getByRole('button', { name: /Review/ }).click();
  await p.screenshot({ path: S+'/8-done.png' });
  await p.getByRole('button', { name: /Plan my week/ }).click();
  const r = await p.evaluate(() => window.__done);
  console.log('have', r.haveIds.length, 'custom', r.customItems.map(c=>c.name), 'staples', r.staples.map(s=>s.name).join(', '));
  const dark = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark' });
  const d = await dark.newPage(); await d.goto('http://localhost:4173'); await d.getByRole('button', { name: "Let's go" }).click();
  await d.screenshot({ path: S+'/9-dark.png' });
  console.log('errors', errs);
  await b.close();
})();
